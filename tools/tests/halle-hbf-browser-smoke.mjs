import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:768,height:1024},deviceScaleFactor:1,hasTouch:true});
const errors=[];page.on('pageerror',err=>errors.push(err.message));page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
try{
 await page.goto('http://127.0.0.1:8765/index.html?v=halle-start-test',{waitUntil:'domcontentloaded'});
 const buttons=page.locator('#stCards button');
 const halle=buttons.filter({hasText:'Halle Hbf'});
 await halle.first().waitFor({timeout:20000});
 assert.equal(await halle.count(),1,'There must be exactly one Halle start card');
 assert.equal(await halle.first().isEnabled(),true,'Halle game start must be enabled');
 await halle.first().click();
 await page.waitForURL('**/halle-hbf-play.html*',{timeout:12000});
 await page.locator('#departures button[data-service]').first().waitFor({timeout:22000});
 assert.equal(await page.locator('#departures button[data-service]').count(),33);
 assert.equal(await page.locator('#schematicWorld').getAttribute('display'),'inline','Player view must be a dedicated schematic, not rotated OSM');
 assert.equal(await page.locator('#schematicWorld #schemaLabels [data-track-ref]').count(),17,'13 platform and 4 stabling indicator rows');
 assert.equal(await page.locator('#schematicWorld #schemaRails line.schemaRail').count(),1253,'Every OSM edge drawn exactly once on Gleisbild');
 assert.equal(await page.locator('#schematicWorld #schemaHits [data-edge]').count(),1253,'All schematic rails remain touch selectable');
 const y1=Number(await page.locator('#schemaLabels [data-track-ref="1"] circle').getAttribute('cy'));
 const y2=Number(await page.locator('#schemaLabels [data-track-ref="2"] circle').getAttribute('cy'));
 assert.ok(y2-y1>=55,'Gleisbild tracks need real horizontal spacing, not a rotated narrow map');
 await page.screenshot({path:'halle-gleisbild-west.png',fullPage:false});
 const zoomBefore=await page.locator('#board').getAttribute('viewBox');
 await page.locator('#zoomIn').click();
 const zoomAfter=await page.locator('#board').getAttribute('viewBox');
 assert.notEqual(zoomBefore,zoomAfter,'Toolbar zoom should update the track map');
 assert.equal(await page.locator('#nextTrain').isVisible(),true,'Guided train choice should be visible');
 await page.locator('#nextTrain').click();
 assert.match(await page.locator('#selectedService').innerText(),/05:00/,'Next-train shortcut should select first scheduled departure');
 assert.equal(await page.locator('details.technical').evaluate(el=>el.open),false,'Dense OSM source information should be collapsed initially');
 const status=await page.locator('#status').innerText();
 assert.doesNotMatch(status,/Fehler beim Laden|konnte nicht geladen/);
 await page.locator('#departures button[data-service]').first().click();
 const signal=await page.locator('#virtualAspect').innerText();
 assert.match(signal,/Hp0/,'Signal should start at stop');
 assert.equal(await page.locator('#clearRoute').isEnabled(),true,'First scheduled train needs playable test route');
 await page.locator('#clearRoute').click();
 assert.equal(await page.locator('#schemaLabels [data-track-ref="1"] circle').getAttribute('fill'),'#4cea9b','Schematic virtual departure signal lamp must change to proceed');
 assert.match(await page.locator('#virtualAspect').innerText(),/Ks1/,'Signal should be cleared');
 assert.equal(await page.locator('#go').isEnabled(),true,'05:00 train must be dispatchable at 05:00');
 await page.locator('#go').click();
 assert.match(await page.locator('#virtualAspect').innerText(),/Hp0/,'Signal must fall to stop during train run');
 await page.locator('#departures button[data-service]').first().locator('.state').getByText('abgefahren').waitFor({timeout:45000});
 assert.match(await page.locator('#score').innerText(),/1\/33/,'Progress should count the first completed train');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('#map').isVisible(),true,'Map should remain visible on a phone');
 assert.equal(await page.locator('#go').isVisible(),true,'Dispatch action should stay accessible on a phone');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3),'No horizontal overflow on phone');
 await page.locator('#nextTrain').click();
 assert.notEqual(await page.locator('#selectedService').innerText(),'Wähle einen Zug aus der Original-Abfahrtstafel.');
 await page.locator('details.technical summary').click();
 assert.equal(await page.locator('#objectSummary').isVisible(),true,'Technical review panel must remain accessible');
 assert.equal(await page.locator('#sectorTabs [data-sector]').count(),4,'Four area tabs expected');
 assert.match(await page.locator('.mapHud').innerText(),/SCHEMATISCHES/,'Schematic should be default');
 const originalView=await page.locator('#board').getAttribute('viewBox');
 await page.locator('[data-sector="ost"]').click();
 await page.screenshot({path:'halle-gleisbild-ost.png',fullPage:false});
 assert.equal(await page.locator('[data-sector="ost"]').getAttribute('aria-pressed'),'true');
 assert.notEqual(await page.locator('#board').getAttribute('viewBox'),originalView,'Other desk should frame different tracks');
 await page.locator('#sectorViewMode').click();
 assert.match(await page.locator('.mapHud').innerText(),/ORIGINALGEOMETRIE/);
 await page.locator('#sectorViewMode').click();
 assert.match(await page.locator('.mapHud').innerText(),/SCHEMATISCHES/);
 await page.locator('[data-sector="ww"]').click();
 await page.screenshot({path:'halle-gleisbild-weichenwaerter.png',fullPage:false});
 assert.equal(await page.locator('#wwDesk').isVisible(),true,'Weichenwaerter needs a working dedicated desk');
 assert.equal(await page.locator('.dispatchDesk').first().isVisible(),false,'Dispatch desk should be hidden during stabling');
 await page.locator('#shunt136').click();
 assert.equal(await page.locator('#shuntRelease').isEnabled(),true,'Stabling should provide a checked geometric route');
 await page.locator('#shuntRelease').click();
 assert.equal(await page.locator('#shuntStart').isEnabled(),true,'Shunting requires explicit virtual release');
 await page.locator('#shuntStart').click();
 await page.locator('#shuntStatus').getByText(/abgeschlossen/).waitFor({timeout:45000});
 assert.match(await page.locator('#shuntCount').innerText(),/1/,'Shunt finish must count separately from timetable');
 assert.match(await page.locator('#score').innerText(),/1\/33/,'Simulated shunting must not score as an original DB departure');
 await page.locator('[data-sector="west"]').click();
 assert.equal(await page.locator('.dispatchDesk').first().isVisible(),true);
 assert.equal(errors.length,0,'Browser errors: '+errors.join(' | '));
 console.log(JSON.stringify({passed:true,halleCards:await halle.count(),departures:33,firstTrainCompleted:true,errors,finalStatus:await page.locator('#status').innerText()}));
}finally{await browser.close();}
